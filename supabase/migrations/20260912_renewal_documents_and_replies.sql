-- 4. Automated Status Synchronization Trigger
-- When all 4 documents are Approved, profiles.requirements_status is set to 'Complete'.
-- Otherwise, if any document is missing, pending, or rejected, it is set to 'Lacking'.
create or replace function public.sync_student_renewal_status() returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_approved_count int;
  v_student_id uuid;
begin
  v_student_id := coalesce(new.student_id, old.student_id);
  
  select count(*) into v_approved_count
  from public.renewal_documents
  where student_id = v_student_id
    and academic_year = coalesce(new.academic_year, old.academic_year, '2026-2027')
    and semester = coalesce(new.semester, old.semester, '1st Semester')
    and status = 'Approved';

  if v_approved_count >= 4 then
    update public.profiles
    set requirements_status = 'Complete', updated_at = now()
    where id = v_student_id;
  else
    update public.profiles
    set requirements_status = 'Lacking', updated_at = now()
    where id = v_student_id;
  end if;

  return new;
end $$;

drop trigger if exists on_renewal_document_changed on public.renewal_documents;
create trigger on_renewal_document_changed
after insert or update or delete on public.renewal_documents
for each row execute procedure public.sync_student_renewal_status();

-- 5. Row Level Security (RLS)
alter table public.renewal_documents enable row level security;

drop policy if exists "Renewal docs: student read own" on public.renewal_documents;
create policy "Renewal docs: student read own" on public.renewal_documents
  for select using (student_id = auth.uid());

drop policy if exists "Renewal docs: student insert own" on public.renewal_documents;
create policy "Renewal docs: student insert own" on public.renewal_documents
  for insert with check (student_id = auth.uid());

drop policy if exists "Renewal docs: student update own" on public.renewal_documents;
create policy "Renewal docs: student update own" on public.renewal_documents
  for update using (student_id = auth.uid() and status in ('Pending', 'Rejected'))
  with check (student_id = auth.uid());

drop policy if exists "Renewal docs: admin manage all" on public.renewal_documents;
create policy "Renewal docs: admin manage all" on public.renewal_documents
  for all using (public.is_admin()) with check (public.is_admin());

