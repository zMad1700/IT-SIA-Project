-- Enhances ScholarHub schema with Renewal Documents tracking, auto-sync triggers, and Help Ticket replies.

-- 1. Renewal Documents Table
create table if not exists public.renewal_documents (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  document_type text not null check (document_type in ('COG', 'COR', 'Student ID', 'Barangay Clearance')),
  academic_year text not null default '2026-2027',
  semester text not null default '1st Semester' check (semester in ('1st Semester', '2nd Semester', 'Summer')),
  file_url text not null,
  file_name text not null,
  file_size bigint,
  status text not null default 'Pending' check (status in ('Pending', 'Approved', 'Rejected')),
  reviewer_id uuid references public.profiles(id) on delete set null,
  reviewer_notes text,
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(student_id, document_type, academic_year, semester)
);

create index if not exists renewal_docs_student_idx on public.renewal_documents(student_id);
create index if not exists renewal_docs_status_idx on public.renewal_documents(status);

