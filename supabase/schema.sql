create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique, name text not null,
  first_name text, middle_name text, last_name text, phone text, sex text,
  birth_date date, purok text, barangay text, municipality text,
  school text references public.schools(name) on update cascade,
  year_level text, course text,
  scholar_type text check (scholar_type in ('Old scholar', 'New scholar')),
  role text not null default 'user' check (role in ('user', 'admin')),
  photo text, bio text,
  requirements_status text not null default 'Complete' check (requirements_status in ('Complete', 'Lacking')),
  scholar_status text not null default 'Active' check (scholar_status in ('Active', 'Non-active')),
  added_by_admin boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table public.profiles add column if not exists municipality text;
alter table public.profiles add column if not exists updated_at timestamptz not null default now();
do $$ begin
  if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'profiles' and column_name = 'municipaligitty') then
    execute 'update public.profiles set municipality = coalesce(municipality, municipaligitty)';
  end if;
end $$;

create table if not exists public.scholarships (
  id bigint generated by default as identity primary key,
  title text not null, category text, description text, amount numeric(12,2) check (amount >= 0), deadline timestamptz,
  status text not null default 'Open' check (status in ('Draft', 'Open', 'Closed')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.requirements (
  id bigint generated by default as identity primary key,
  scholarship_id bigint not null references public.scholarships(id) on delete cascade,
  title text not null, description text, is_required boolean not null default true,
  created_at timestamptz not null default now(), unique(scholarship_id, title)
);
create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  scholarship_id bigint not null references public.scholarships(id) on delete restrict,
  status text not null default 'Draft' check (status in ('Draft', 'Submitted', 'Under review', 'Approved', 'Rejected')),
  submitted_at timestamptz, reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz, reviewer_notes text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique(student_id, scholarship_id)
);
create table if not exists public.application_requirements (
  id bigint generated by default as identity primary key,
  application_id bigint not null references public.applications(id) on delete cascade,
  requirement_id bigint not null references public.requirements(id) on delete cascade,
  file_path text, status text not null default 'Pending' check (status in ('Pending', 'Submitted', 'Accepted', 'Rejected')),
  reviewed_by uuid references public.profiles(id) on delete set null, reviewed_at timestamptz, notes text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique(application_id, requirement_id)
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  author_id uuid references public.profiles(id) on delete set null,
  message text not null check (char_length(message) <= 1000),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.announcement_reactions (
  announcement_id bigint not null references public.announcements(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  reaction text not null check (reaction in ('like', 'heart')),
  created_at timestamptz not null default now(), primary key(announcement_id, user_id)
);
create table if not exists public.help_requests (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  subject text not null check (char_length(subject) <= 100), message text not null check (char_length(message) <= 1000),
  status text not null default 'Pending' check (status in ('Pending', 'Resolved')),
  resolved_by uuid references public.profiles(id) on delete set null, resolved_at timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table public.announcements add column if not exists pinned boolean not null default false;
alter table public.help_requests add column if not exists admin_reply text check (char_length(admin_reply) <= 2000);
alter table public.help_requests add column if not exists replied_by uuid references public.profiles(id) on delete set null;
alter table public.help_requests add column if not exists replied_at timestamptz;
alter table public.help_requests add column if not exists archived_at timestamptz;
create table if not exists public.renewal_schedules (
  id bigint generated by default as identity primary key,
  school_name text not null unique references public.schools(name) on update cascade on delete cascade,
  deadline_at timestamptz, schedule_at timestamptz,
  updated_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(), check (deadline_at is not null or schedule_at is not null)
);
create index if not exists applications_student_id_idx on public.applications(student_id);
create index if not exists applications_scholarship_id_idx on public.applications(scholarship_id);
create index if not exists help_requests_student_id_idx on public.help_requests(student_id);
create index if not exists help_requests_archived_at_idx on public.help_requests(archived_at);
create index if not exists requirements_scholarship_id_idx on public.requirements(scholarship_id);
create index if not exists app_req_application_id_idx on public.application_requirements(application_id);
create index if not exists app_req_requirement_id_idx on public.application_requirements(requirement_id);
create index if not exists reactions_user_id_idx on public.announcement_reactions(user_id);
create index if not exists announcements_author_id_idx on public.announcements(author_id);
create index if not exists scholarships_created_by_idx on public.scholarships(created_by);

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id,email,name,first_name,middle_name,last_name,phone,sex,birth_date,purok,barangay,municipality,school,year_level,course,scholar_type)
  values (new.id,new.email,coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),new.raw_user_meta_data ->> 'first_name',new.raw_user_meta_data ->> 'middle_name',new.raw_user_meta_data ->> 'last_name',new.raw_user_meta_data ->> 'phone',new.raw_user_meta_data ->> 'sex',nullif(new.raw_user_meta_data ->> 'birth_date','')::date,new.raw_user_meta_data ->> 'purok',new.raw_user_meta_data ->> 'barangay',new.raw_user_meta_data ->> 'municipality',new.raw_user_meta_data ->> 'school',new.raw_user_meta_data ->> 'year_level',new.raw_user_meta_data ->> 'course',new.raw_user_meta_data ->> 'scholar_type');
  return new;
end $$;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;
create or replace function public.set_updated_at() returns trigger language plpgsql set search_path = public as $$ begin new.updated_at = now(); return new; end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
do $$ declare tab text; begin
  foreach tab in array array['profiles','scholarships','applications','application_requirements','announcements','help_requests','renewal_schedules'] loop
    execute format('drop trigger if exists %I on public.%I', tab || '_set_updated_at', tab);
    execute format('create trigger %I before update on public.%I for each row execute procedure public.set_updated_at()', tab || '_set_updated_at', tab);
  end loop;
end $$;

