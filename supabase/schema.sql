drop policy if exists "Profiles: own read" on public.profiles; drop policy if exists "Profiles: admin read" on public.profiles; drop policy if exists "Profiles: own update" on public.profiles; drop policy if exists "Profiles: admin manage" on public.profiles;
create policy "Profiles: own read" on public.profiles for select using (auth.uid() = id);
create policy "Profiles: admin read" on public.profiles for select using (public.is_admin());
create policy "Profiles: own update" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id and role = 'user');
create policy "Profiles: admin manage" on public.profiles for all using (public.is_admin()) with check (public.is_admin());

